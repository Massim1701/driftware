#!/usr/bin/env python3
"""Karaoke-Fassung pro Song suchen (NUR Studiofassungen, keine Mixe/Remixe/Live/Extended/Edit): das von YouTube automatisch erzeugte
Studio-Audio ("Interpret - Topic", Beschreibung "Auto-generated by YouTube").
Diese Fassung ist exakt die Aufnahme, auf die LRCLIB-Zeitstempel passen --
das Musikvideo (Feld 'yt') hat oft andere Intros/Pausen, deshalb lief der
Karaoke-Text bisher selten synchron.

Ablauf je Song (eindeutig nach Interpret|Titel ueber alle */songs.json):
  1. LRCLIB fragen (gleiche Bereinigung wie ccLyricsClean in shared/
     decades.js). Kein synchroner Text -> fertig, YouTube wird nicht gefragt.
  2. YouTube-Suche (2 Formulierungen), Kandidaten: Kanal ~ Interpret, Titel ~ Titel, Laenge
     hoechstens +-3 s neben einer LRCLIB-Fassung.
  3. Bester Kandidat wird einzeln geprueft: "Auto-generated by YouTube" und
     playable_in_embed.

Ergebnis:
  karaoke/videos.json  {"<a>|<t>": {"yk": <video-id>, "d": <sekunden>, "s": 1 = nur Plattencover}}
                       (laedt die Seite, sobald Karaoke an ist)
  karaoke/status.json  {"<a>|<t>": [<ergebnis>, "<datum>"]} -- was schon
                       versucht wurde; kein_text/kein_topic nach
                       RETRY_DAYS erneut, fehler beim naechsten Lauf.
songs.json wird NICHT angefasst (keine Konflikte mit den anderen Workflows).

Reihenfolge: meistgesehene Songs zuerst (Feld vc). Zeitbudget pro Lauf,
Zwischenspeichern, Schutzschalter: nach MAX_FEHLER_IN_FOLGE YouTube-Fehlern
hintereinander (z.B. Bot-Sperre) bricht der Lauf ab statt weiterzuhaemmern.

Aufruf: python3 tools/fetch_karaoke_videos.py [--limit N]
"""
import argparse
import datetime
import glob
import json
import os
import random
import re
import subprocess
import sys
import time
import unicodedata
import urllib.error
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "karaoke")
VIDEOS_PATH = os.path.join(OUT_DIR, "videos.json")
STATUS_PATH = os.path.join(OUT_DIR, "status.json")
AUSSCHLUSS_PATH = os.path.join(OUT_DIR, "ausschluss.json")

USER_AGENT = "DriftwareCatalogBot/1.0 +https://driftware.online"
TIME_BUDGET_SECONDS = int(os.environ.get("KARAOKE_TIME_BUDGET_SECONDS", "18000"))  # 5h
SAVE_EVERY = 20
RETRY_DAYS = 90
DURATION_TOLERANCE = 3.0
MAX_FEHLER_IN_FOLGE = 8
START_TS = time.time()
TODAY = datetime.date.today().isoformat()

# Nur Studiofassungen: Songs/Videos mit diesen Woertern im Titel werden uebersprungen.
# "Album/Single/Original Version" und "Remaster" sind ebenfalls Studio und bleiben erlaubt.
KEIN_STUDIO = re.compile(
    r"remix|\bmix\b|mixes|megamix|\bedit\b|\blive\b|extended|instrumental|acoustic|\bdub\b|club|"
    r"\bdemo\b|medley|reprise|karaoke|cover|tribute|sound-?a-?like|\bep\b|re-?record|"
    r"\d+\"|\bversion\b|\bver\.|bootleg|rework|\bvip\b|radio|clean|explicit|sped|slowed|8d|nightcore",
    re.IGNORECASE)
STUDIO_ERLAUBT = re.compile(r"(album|single|original|remaster(ed)?|stereo|mono)\s+(version|edit|mix)?|remaster(ed)?", re.IGNORECASE)


def ist_studio_titel(raw):
    """False bei Mix/Live/Extended u. ae. -- nur in Zusaetzen (Klammern, ' - Zusatz') und bei
    eindeutigen Woertern (Remix/Megamix), damit Titel wie "Live To Tell" oder "Radio Ga Ga" bleiben."""
    s = str(raw or "")
    if re.search(r"remix|megamix|\bmixes\b", s, re.IGNORECASE):
        return False
    extras = re.findall(r"[\(\[]([^\)\]]*)[\)\]]", s)
    m = re.search(r"\s-\s(.*)$", s)
    if m:
        extras.append(m.group(1))
    for e in extras:
        e = STUDIO_ERLAUBT.sub(" ", e)
        if KEIN_STUDIO.search(e) or re.search(r"\b(live|mix|edit)\b", e, re.IGNORECASE):
            return False
    return True


AUSSCHLUSS = set()


def load_json(path, default):
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    return default


def save_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(data, f, separators=(",", ":"), ensure_ascii=False, sort_keys=True)
    os.replace(tmp, path)


# ------------------------------------------------------------ Normalisierung

def lyrics_clean(s):
    """Wie ccLyricsClean in shared/decades.js."""
    s = re.sub(r"\s*[\(\[][^\)\]]*[\)\]]", "", str(s or ""))
    s = re.sub(r"\s+-\s+.*$", "", s)
    s = re.sub(r"\s+(feat\.?|ft\.?|featuring)\s+.*$", "", s, flags=re.IGNORECASE)
    return s.strip()


def lyrics_artist(a):
    """Wie ccLyricsFetch: nur der erste Interpret."""
    return lyrics_clean(re.split(r",|&| x | und ", str(a or ""), flags=re.IGNORECASE)[0])


def norm(s):
    s = unicodedata.normalize("NFKD", s or "")
    s = "".join(ch for ch in s if not unicodedata.combining(ch)).lower().replace("&", "and")
    s = s.rstrip("*")
    s = re.sub(r"\s*\(\d+\)\s*$", "", s)
    if s.startswith("the "):
        s = s[4:]
    return "".join(ch for ch in s if ch.isalnum())


def song_key(s):
    return f"{s.get('a')}|{s.get('t')}"  # identisch zu ccLyricsSongKey


# ------------------------------------------------------------ LRCLIB

def lrclib_durations(artist, title):
    q = urllib.parse.urlencode({"track_name": lyrics_clean(title), "artist_name": lyrics_artist(artist)})
    req = urllib.request.Request("https://lrclib.net/api/search?" + q, headers={"User-Agent": USER_AGENT})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                data = json.loads(resp.read().decode("utf-8"))
            return sorted({round(x["duration"]) for x in data
                           if x.get("syncedLyrics") and not x.get("instrumental") and x.get("duration")})
        except urllib.error.HTTPError as e:
            if e.code == 429 or e.code >= 500:
                time.sleep(5 * (attempt + 1))
                continue
            return None
        except Exception:
            time.sleep(3 * (attempt + 1))
    return None


# ------------------------------------------------------------ YouTube

class YouTubeFehler(Exception):
    pass


def yt_json(args, timeout=60):
    try:
        p = subprocess.run(["yt-dlp", *args, "-J", "--no-warnings", "--skip-download"],
                           capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        raise YouTubeFehler("Zeitueberschreitung")
    if p.returncode != 0 or not p.stdout.strip():
        err = (p.stderr or "").strip().splitlines()
        raise YouTubeFehler(err[-1][:200] if err else f"Exit {p.returncode}")
    return json.loads(p.stdout)


STANDBILD_MAX_DIFF = 8.0  # mittlere Helligkeitsabweichung 0-255; Standbild ~0-3, echtes Video >15


def ensure_pillow():
    """Pillow fuer die Cover-Erkennung; fehlt es (der Workflow installiert es nicht), wird es einmal nachinstalliert."""
    try:
        import PIL  # noqa: F401
        return True
    except ImportError:
        pass
    try:
        subprocess.run([sys.executable, "-m", "pip", "install", "--quiet", "pillow"], check=True, timeout=240)
        import PIL  # noqa: F401
        return True
    except Exception as e:
        print(f"::warning::Pillow nicht verfuegbar, keine Cover-Erkennung: {str(e)[:100]}")
        return False


def ist_standbild(vid):
    """True = nur Plattencover (die 3 Vorschaubilder 1/2/3.jpg von i.ytimg.com sind praktisch gleich),
    False = bewegtes Video, None = nicht feststellbar. Ohne Anmeldung, nicht bot-gesperrt wie yt-dlp-Einzelabrufe."""
    try:
        from PIL import Image, ImageChops, ImageStat
        import io
        frames = []
        for i in (1, 2, 3):
            req = urllib.request.Request(f"https://i.ytimg.com/vi/{vid}/{i}.jpg", headers={"User-Agent": USER_AGENT})
            with urllib.request.urlopen(req, timeout=20) as r:
                frames.append(Image.open(io.BytesIO(r.read())).convert("L"))
        diff = max(ImageStat.Stat(ImageChops.difference(frames[0], f)).mean[0] for f in frames[1:])
        return diff <= STANDBILD_MAX_DIFF
    except Exception:
        return None


def waehle(cands):
    """cands: [(video-id, sekunden)] nach Prioritaet. Einbettbare Kandidaten (hoechstens 3) pruefen,
    Standbild (Plattencover = reine Studio-Aufnahme) vor bewegtem Video; "s": 1 markiert ein Standbild."""
    fallback = None
    for vid, dur in cands[:3]:
        if not embeddable(vid):
            time.sleep(random.uniform(0.3, 0.6))
            continue
        still = ist_standbild(vid)
        if still:
            return {"yk": vid, "d": int(dur), "s": 1}
        if fallback is None:
            fallback = {"yk": vid, "d": int(dur)}
    return fallback


def find_audio_upload(artist, title, durations):
    """Direkt bei YouTube: Upload des Interpreten/Labels mit nacktem Titel und passender Laenge; Topic und
    "Official Audio" werden bevorzugt, kein Mix/Live/Lyric-Video."""
    a_key = norm(lyrics_artist(artist))
    t_key = norm(lyrics_clean(title))
    res = yt_json([f"ytsearch10:{lyrics_artist(artist)} {lyrics_clean(title)} official audio", "--flat-playlist"])
    res = {"entries": (res.get("entries") or []) + (yt_json([f"ytsearch10:{lyrics_artist(artist)} {lyrics_clean(title)}", "--flat-playlist"]).get("entries") or [])}
    cands = []
    for e in res.get("entries") or []:
        raw = e.get("title") or ""
        low = raw.lower()
        ch_raw = e.get("channel") or e.get("uploader") or ""
        is_topic = bool(re.search(r"-\s*topic$", ch_raw, flags=re.IGNORECASE))
        is_audio = is_topic or bool(re.search(r"\b(official audio|audio only|\(audio\)|\[audio\])", low))
        if re.search(r"official video|music video|\blyrics?\b|visuali[sz]er|\blive\b|remix|\bmix\b|cover|reaction|karaoke|instrumental|\d+d audio|slowed|sped|nightcore", low):
            continue
        rest = re.sub(r"[\(\[]\s*(official\s+)?(audio|hd|hq|4k|explicit|clean)[^\)\]]*[\)\]]", " ", raw, flags=re.IGNORECASE)
        rest = re.sub(r"\bofficial\s+audio\b", " ", rest, flags=re.IGNORECASE)
        head, sep, tail = rest.partition(" - ")
        if sep and a_key and (a_key in norm(head) or norm(head) in a_key):
            rest = tail
        if not ist_studio_titel(rest) or norm(lyrics_clean(rest)) != t_key:
            continue
        ch = norm(re.sub(r"\s*-\s*topic$", "", ch_raw, flags=re.IGNORECASE))
        artist_ok = bool(ch) and (ch == a_key or (len(ch) > 3 and len(a_key) > 3 and (ch in a_key or a_key in ch)) or "vevo" in ch)
        if not artist_ok and not (sep and a_key in norm(head)):
            continue
        dur = e.get("duration")
        if not e.get("id") or not dur:
            continue
        diff = min(abs(dur - d) for d in durations)
        if diff <= DURATION_TOLERANCE:
            cands.append((0 if is_topic else 1 if is_audio else 2, diff, -(e.get("view_count") or 0), e["id"], dur))
    return waehle([(vid, dur) for _, diff, _, vid, dur in sorted(cands)])


def find_topic_video(artist, title, durations):
    a_key = norm(lyrics_artist(artist))
    t_key = norm(lyrics_clean(title))
    # 1. Versuch "... topic"; bei grossen Stars verdraengen Fan-Uploads das
    # Studio-Audio, dann 2. Versuch ueber dessen Beschreibungstext.
    for query in (f"ytsearch10:{lyrics_artist(artist)} {lyrics_clean(title)} topic",
                  f'ytsearch10:"{lyrics_clean(title)}" {lyrics_artist(artist)} "provided to youtube by"'):
        hit = _pick(yt_json([query, "--flat-playlist"]), a_key, t_key, durations)
        if hit:
            return hit
        time.sleep(random.uniform(0.5, 1.0))
    return None


def embeddable(vid):
    """Einbettbar? oEmbed braucht keine Anmeldung (yt-dlp-Einzelabruf wird
    von GitHub-Servern als Bot abgewiesen). 401/403 = nicht einbettbar."""
    url = "https://www.youtube.com/oembed?format=json&url=" + urllib.parse.quote(f"https://www.youtube.com/watch?v={vid}", safe="")
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": USER_AGENT}), timeout=20):
            return True
    except urllib.error.HTTPError as e:
        if e.code in (401, 403, 404):
            return False
        raise YouTubeFehler(f"oEmbed {e.code}")
    except Exception as e:
        raise YouTubeFehler(f"oEmbed {type(e).__name__}")


def _pick(res, a_key, t_key, durations):
    cands = []
    for e in res.get("entries") or []:
        ch = norm(re.sub(r"\s*-\s*topic$", "", e.get("channel") or e.get("uploader") or "", flags=re.IGNORECASE))
        raw_title = e.get("title") or ""
        head, sep, tail = raw_title.partition(" - ")
        if sep and norm(head) == ch:
            raw_title = tail  # manche Topic-Titel heissen "Interpret - Titel"
        if not ist_studio_titel(raw_title):
            continue  # Mix/Live/Extended/Edit-Video: nie als Karaoke-Fassung nehmen
        et = norm(lyrics_clean(raw_title))
        dur = e.get("duration")
        if not e.get("id") or not dur or not ch or not et:
            continue
        artist_ok = ch == a_key or (len(ch) > 3 and len(a_key) > 3 and (ch in a_key or a_key in ch))
        if not artist_ok or et != t_key:
            continue  # Studio-Audio traegt den nackten Titel, ohne "Interpret - "
        diff = min(abs(dur - d) for d in durations)
        if diff <= DURATION_TOLERANCE:
            is_topic = bool(re.search(r"-\s*topic$", (e.get("channel") or e.get("uploader") or ""), flags=re.IGNORECASE))
            if is_topic:  # nur echte "Interpret - Topic"-Kanaele (Studio-Audio)
                cands.append((diff, -(e.get("view_count") or 0), e["id"], dur))
    return waehle([(vid, dur) for diff, _, vid, dur in sorted(cands)])


def nachpruefen(videos, songs, maximum):
    """Alte Treffer (ohne Feld "s") nebenbei pruefen: Plattencover -> "s": 1; Video -> nach einem Cover suchen und
    ersetzen, sonst "s": 0 (wird nicht erneut geprueft). Hoechstens `maximum` Eintraege pro Lauf."""
    if maximum <= 0 or not ensure_pillow():
        return
    by_key = {song_key(x): x for x in songs}
    offen = [k for k, v in videos.items() if "s" not in v]
    print(f"Nachpruefen: {len(offen)} Treffer ohne Cover-Pruefung, jetzt hoechstens {maximum}.")
    n = {"cover": 0, "ersetzt": 0, "video": 0, "unklar": 0}
    fehler = 0
    for k in offen[:maximum]:
        if time.time() - START_TS > TIME_BUDGET_SECONDS * 0.2:
            break
        v = videos[k]
        still = ist_standbild(v["yk"])
        if still is None:
            n["unklar"] += 1
            continue
        if still:
            v["s"] = 1
            n["cover"] += 1
            continue
        song = by_key.get(k)
        hit = None
        if song:
            try:
                durations = lrclib_durations(song["a"], song["t"])
                if durations:
                    hit = find_topic_video(song["a"], song["t"], durations) or find_audio_upload(song["a"], song["t"], durations)
                fehler = 0
            except YouTubeFehler as e:
                fehler += 1
                print(f"  Nachpruefen: YouTube-Fehler ({fehler}): {e}")
                if fehler >= 3:
                    break
                continue
            time.sleep(random.uniform(1.0, 2.0))
        if hit and hit.get("s"):
            videos[k] = hit
            n["ersetzt"] += 1
        else:
            v["s"] = 0
            n["video"] += 1
    print(f"Nachpruefen fertig: {n}")


# ------------------------------------------------------------ Ablauf

def collect_songs():
    """Eindeutige Songs ueber alle Seiten, meistgesehene zuerst."""
    songs = {}
    for path in glob.glob(os.path.join(ROOT, "*-music", "songs.json")):
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        lists = [v for k, v in data.items() if k != "Karaoke" and k != "TextLaeuftMit"] if isinstance(data, dict) else [data]
        for lst in lists:
            if not isinstance(lst, list):
                continue
            for s in lst:
                if not isinstance(s, dict) or not s.get("a") or not s.get("t") or not s.get("yt"):
                    continue
                k = song_key(s)
                if k in AUSSCHLUSS or not ist_studio_titel(s["t"]):
                    continue  # Remix/Live/Mix-Songs kommen nie in die Karaoke-Kachel
                if k not in songs or (s.get("vc") or 0) > (songs[k].get("vc") or 0):
                    songs[k] = s
    return sorted(songs.values(), key=lambda s: -(s.get("vc") or 0))


def due(entry):
    if not entry:
        return True
    result, date = entry
    if result == "ok":
        return False
    if result == "fehler":
        return True
    try:
        age = (datetime.date.today() - datetime.date.fromisoformat(date)).days
    except ValueError:
        return True
    return age >= RETRY_DAYS


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=0, help="hoechstens N Songs (0 = bis Zeitbudget)")
    ap.add_argument("--recheck", type=int, default=150, help="hoechstens N alte Treffer pro Lauf auf Plattencover pruefen (0 = aus)")
    args = ap.parse_args()

    global AUSSCHLUSS
    AUSSCHLUSS = set((load_json(AUSSCHLUSS_PATH, {}) or {}).get("songs", []))
    videos = load_json(VIDEOS_PATH, {})
    status = load_json(STATUS_PATH, {})
    songs = collect_songs()
    todo = [s for s in songs if due(status.get(song_key(s)))]
    print(f"{len(songs)} Songs gesamt, {len(videos)} mit Karaoke-Fassung, {len(todo)} offen.")
    ensure_pillow()
    nachpruefen(videos, songs, args.recheck)
    save_json(VIDEOS_PATH, videos)

    counts = {"ok": 0, "kein_text": 0, "kein_topic": 0, "fehler": 0}
    fehler_in_folge = 0
    done = 0
    for s in todo:
        if time.time() - START_TS > TIME_BUDGET_SECONDS:
            print("Zeitbudget erreicht, Rest folgt im naechsten Lauf.")
            break
        if args.limit and done >= args.limit:
            break
        k = song_key(s)
        durations = lrclib_durations(s["a"], s["t"])
        if durations is None:
            result = "fehler"
        elif not durations:
            result = "kein_text"
        else:
            try:
                hit = (find_topic_video(s["a"], s["t"], durations)
                       or find_audio_upload(s["a"], s["t"], durations))
                fehler_in_folge = 0
                if hit:
                    videos[k] = hit
                    result = "ok"
                else:
                    result = "kein_topic"
            except YouTubeFehler as e:
                fehler_in_folge += 1
                print(f"  YouTube-Fehler ({fehler_in_folge}/{MAX_FEHLER_IN_FOLGE}): {e}")
                result = "fehler"
            time.sleep(random.uniform(1.0, 2.0))  # YouTube nicht stressen
        status[k] = [result, TODAY]
        counts[result] += 1
        done += 1
        extra = f" -> {videos[k]['yk']} ({videos[k]['d']} s, {'Plattencover' if videos[k].get('s') else 'Video/unklar'})" if result == "ok" else ""
        print(f"[{done}] {s['a']} - {s['t']}: {result}{extra}")
        if done % SAVE_EVERY == 0:
            save_json(VIDEOS_PATH, videos)
            save_json(STATUS_PATH, status)
        if fehler_in_folge >= MAX_FEHLER_IN_FOLGE:
            print("::warning::Zu viele YouTube-Fehler hintereinander (Sperre?) -- Lauf wird beendet, naechster Lauf macht weiter.")
            break
        time.sleep(0.3)  # LRCLIB schonen

    save_json(VIDEOS_PATH, videos)
    save_json(STATUS_PATH, status)
    rest = sum(1 for x in songs if due(status.get(song_key(x))))
    print(f"\nFertig fuer diesen Lauf: {done} bearbeitet {counts}. "
          f"Karaoke-Fassungen gesamt: {len(videos)}. Noch offen: {rest}.")


if __name__ == "__main__":
    main()
